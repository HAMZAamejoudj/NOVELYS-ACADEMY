'use client';

import React, { useState } from 'react';
import { PageHeader } from '../../components/layout/PageHeader';
import {
  Plus,
  Phone,
  Mail,
  Percent,
  Layers,
  DollarSign,
  TrendingUp,
  X,
} from 'lucide-react';
import { FaUserGraduate, FaCircleCheck, FaTrashCan } from 'react-icons/fa6';
import { mockGroupes, mockEtudiants } from '../../data/mockData';
import { formatDH } from '../../lib/utils';
import { Professeur } from '../../types';
import { useMatieres } from '../../data/matieresStore';
import { useProfesseurs } from '../../data/appStores';
import { DeleteConfirmModal } from '../../components/common/DeleteConfirmModal';

export default function ProfesseursPage() {
  const { professeurs: profsList, addProfesseur, deleteProfesseur } = useProfesseurs();
  const [isModalOpen, setIsModalOpen] = useState(false);
  const [deleteTarget, setDeleteTarget] = useState<{ id: string; name: string } | null>(null);
  const [toastMessage, setToastMessage] = useState<string | null>(null);
  const { matieres, addMatiere } = useMatieres();
  const [isAddingNewMatiere, setIsAddingNewMatiere] = useState(false);
  const [quickMatiereInput, setQuickMatiereInput] = useState('');

  // Form State
  const [nom, setNom] = useState('');
  const [prenom, setPrenom] = useState('');
  const [telephone, setTelephone] = useState('');
  const [email, setEmail] = useState('');
  const [matiere, setMatiere] = useState('Mathématiques');
  const [pourcentage, setPourcentage] = useState(60);

  const showToast = (msg: string) => {
    setToastMessage(msg);
    setTimeout(() => setToastMessage(null), 3500);
  };

  const handleAddProf = (e: React.FormEvent) => {
    e.preventDefault();
    if (!nom || !prenom || !telephone) return;

    const newProf: Professeur = {
      id: `prof-${Date.now()}`,
      nom,
      prenom,
      telephone,
      email: email || `${prenom.toLowerCase()}.${nom.toLowerCase()}@educenter.ma`,
      matieres: [matiere],
      statut: 'actif',
      pourcentage: Number(pourcentage),
      groupesIds: [],
    };

    addProfesseur(newProf);
    setIsModalOpen(false);
    showToast(`Professeur Pr. ${prenom} ${nom} ajouté avec succès !`);
    setNom('');
    setPrenom('');
    setTelephone('');
    setEmail('');
    setPourcentage(60);
  };

  return (
    <div className="space-y-6 w-full">
      <PageHeader
        title="Gestion des Professeurs"
        description="Gérez les enseignants du centre, leurs matières et leurs pourcentages sur les cotisations."
        badge={`${profsList.length} professeurs`}
        icon={FaUserGraduate}
        action={{
          label: 'Nouveau Professeur',
          icon: Plus,
          onClick: () => setIsModalOpen(true),
        }}
      />

      {/* Teachers Grid Cards */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 xl:grid-cols-3 2xl:grid-cols-4 gap-5 w-full">
        {profsList.map((prof) => {
          const profGroups = mockGroupes.filter((g) => g.professeurId === prof.id);

          // Calculate estimated revenue generated by this prof's groups
          let totalCotisations = 0;
          profGroups.forEach((grp) => {
            const nbEleves = mockEtudiants.filter((e) => e.groupesIds.includes(grp.id)).length;
            totalCotisations += nbEleves * grp.tarifMensuel;
          });
          const partProf = (totalCotisations * prof.pourcentage) / 100;
          const partCentre = totalCotisations - partProf;

          return (
            <div
              key={prof.id}
              className="bg-white rounded-2xl border border-slate-200/90 shadow-xs hover:shadow-md transition-shadow p-5 flex flex-col justify-between"
            >
              <div>
                {/* Header Profile */}
                <div className="flex items-start justify-between">
                  <div className="flex items-center gap-3">
                    <div className="w-12 h-12 rounded-xl bg-gradient-to-tr from-indigo-500 to-blue-600 text-white font-bold text-base flex items-center justify-center shadow-xs">
                      {prof.prenom[0]}
                      {prof.nom[0]}
                    </div>
                    <div>
                      <h3 className="font-bold text-slate-900 text-base">
                        Pr. {prof.prenom} {prof.nom}
                      </h3>
                      <div className="flex flex-wrap gap-1 mt-1">
                        {prof.matieres.map((m, idx) => (
                          <span
                            key={idx}
                            className="text-[11px] font-semibold px-2 py-0.5 rounded bg-blue-50 text-blue-700"
                          >
                            {m}
                          </span>
                        ))}
                      </div>
                    </div>
                  </div>

                  <div className="flex items-center gap-1.5">
                    <span
                      className={`text-[11px] font-semibold px-2.5 py-0.5 rounded-full flex items-center gap-1 ${
                        prof.statut === 'actif'
                          ? 'bg-emerald-100 text-emerald-800'
                          : 'bg-slate-100 text-slate-600'
                      }`}
                    >
                      {prof.statut === 'actif' ? (
                        <>
                          <FaCircleCheck className="w-3 h-3 text-emerald-600" />
                          Actif
                        </>
                      ) : (
                        'Inactif'
                      )}
                    </span>

                    <button
                      onClick={() =>
                        setDeleteTarget({
                          id: prof.id,
                          name: `Pr. ${prof.prenom} ${prof.nom}`,
                        })
                      }
                      title="Supprimer ce professeur"
                      className="p-1 rounded-lg text-slate-400 hover:text-rose-600 hover:bg-rose-50 transition-colors cursor-pointer"
                    >
                      <FaTrashCan className="w-3.5 h-3.5" />
                    </button>
                  </div>
                </div>

                {prof.experience && (
                  <p className="text-xs text-slate-500 mt-3 italic bg-slate-50 p-2 rounded-lg border border-slate-100">
                    "{prof.experience}"
                  </p>
                )}

                {/* Contact details */}
                <div className="mt-4 space-y-1.5 text-xs text-slate-600">
                  <div className="flex items-center gap-2">
                    <Phone className="w-3.5 h-3.5 text-slate-400" />
                    <span>{prof.telephone}</span>
                  </div>
                  <div className="flex items-center gap-2">
                    <Mail className="w-3.5 h-3.5 text-slate-400" />
                    <span>{prof.email}</span>
                  </div>
                </div>

                {/* Assigned Groups */}
                <div className="mt-4 pt-3 border-t border-slate-100">
                  <div className="flex items-center justify-between text-xs font-semibold text-slate-500 mb-2">
                    <span className="flex items-center gap-1.5">
                      <Layers className="w-3.5 h-3.5 text-slate-400" />
                      <span>Groupes assignés ({profGroups.length})</span>
                    </span>
                  </div>

                  {profGroups.length > 0 ? (
                    <div className="flex flex-wrap gap-1.5">
                      {profGroups.map((grp) => (
                        <span
                          key={grp.id}
                          className="text-[11px] font-medium px-2 py-1 rounded-md bg-slate-100 text-slate-700 border border-slate-200"
                        >
                          {grp.nom}
                        </span>
                      ))}
                    </div>
                  ) : (
                    <p className="text-xs text-slate-400 italic">Aucun groupe assigné pour le moment</p>
                  )}
                </div>
              </div>

              {/* Remuneration info: Exclusively Percentage */}
              <div className="mt-5 pt-3 border-t border-slate-100 space-y-2">
                <div className="flex items-center justify-between">
                  <span className="text-xs font-semibold text-slate-600 flex items-center gap-1.5">
                    <Percent className="w-4 h-4 text-emerald-600" />
                    <span>Pourcentage Professeur :</span>
                  </span>
                  <span className="text-sm font-extrabold text-emerald-700 bg-emerald-50 px-2.5 py-0.5 rounded-full border border-emerald-200">
                    {prof.pourcentage}%
                  </span>
                </div>

                {/* Ratio Visual bar */}
                <div className="w-full bg-slate-100 h-2 rounded-full overflow-hidden flex">
                  <div
                    style={{ width: `${prof.pourcentage}%` }}
                    className="bg-emerald-500 h-full"
                    title={`Part Prof : ${prof.pourcentage}%`}
                  />
                  <div
                    style={{ width: `${100 - prof.pourcentage}%` }}
                    className="bg-blue-600 h-full"
                    title={`Part Centre : ${100 - prof.pourcentage}%`}
                  />
                </div>

                <div className="flex items-center justify-between text-[11px] text-slate-500 pt-0.5">
                  <span className="text-emerald-700 font-medium">Prof : {prof.pourcentage}%</span>
                  <span className="text-blue-700 font-medium">Centre : {100 - prof.pourcentage}%</span>
                </div>

                {profGroups.length > 0 && (
                  <div className="p-2.5 rounded-lg bg-slate-50 border border-slate-100 flex items-center justify-between text-xs">
                    <span className="text-slate-500">Gain estimé (mois) :</span>
                    <span className="font-bold text-slate-900">{formatDH(partProf)}</span>
                  </div>
                )}
              </div>
            </div>
          );
        })}
      </div>

      {/* Add Professor Modal */}
      {isModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/50 backdrop-blur-xs p-4">
          <div className="bg-white rounded-2xl max-w-lg w-full p-6 shadow-2xl border border-slate-100 animate-in fade-in">
            <div className="flex items-center justify-between pb-3 border-b border-slate-100">
              <h3 className="text-lg font-bold text-slate-900">Ajouter un professeur</h3>
              <button
                onClick={() => setIsModalOpen(false)}
                className="p-1.5 rounded-lg text-slate-400 hover:text-slate-600 hover:bg-slate-100"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <form onSubmit={handleAddProf} className="space-y-4 mt-4">
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">Nom *</label>
                  <input
                    type="text"
                    required
                    value={nom}
                    onChange={(e) => setNom(e.target.value)}
                    placeholder="ex: Alami"
                    className="w-full px-3 py-2 border border-slate-200 rounded-lg text-sm outline-none focus:border-blue-500"
                  />
                </div>
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">Prénom *</label>
                  <input
                    type="text"
                    required
                    value={prenom}
                    onChange={(e) => setPrenom(e.target.value)}
                    placeholder="ex: Mohamed"
                    className="w-full px-3 py-2 border border-slate-200 rounded-lg text-sm outline-none focus:border-blue-500"
                  />
                </div>
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">Téléphone *</label>
                  <input
                    type="text"
                    required
                    value={telephone}
                    onChange={(e) => setTelephone(e.target.value)}
                    placeholder="0661234567"
                    className="w-full px-3 py-2 border border-slate-200 rounded-lg text-sm outline-none focus:border-blue-500"
                  />
                </div>
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">Email</label>
                  <input
                    type="email"
                    value={email}
                    onChange={(e) => setEmail(e.target.value)}
                    placeholder="m.alami@educenter.ma"
                    className="w-full px-3 py-2 border border-slate-200 rounded-lg text-sm outline-none focus:border-blue-500"
                  />
                </div>
              </div>

              <div>
                <div className="flex items-center justify-between mb-1">
                  <label className="text-xs font-semibold text-slate-700">Matière Enseignée</label>
                  <button
                    type="button"
                    onClick={() => setIsAddingNewMatiere(!isAddingNewMatiere)}
                    className="text-[11px] text-blue-600 hover:text-blue-800 font-medium"
                  >
                    {isAddingNewMatiere ? 'Choisir existante' : '+ Nouvelle'}
                  </button>
                </div>

                {isAddingNewMatiere ? (
                  <div className="flex gap-1.5">
                    <input
                      type="text"
                      placeholder="Nom matière..."
                      value={quickMatiereInput}
                      onChange={(e) => setQuickMatiereInput(e.target.value)}
                      className="flex-1 px-2.5 py-1.5 border border-blue-400 rounded-lg text-xs outline-none bg-blue-50/30"
                    />
                    <button
                      type="button"
                      onClick={() => {
                        if (quickMatiereInput.trim()) {
                          addMatiere(quickMatiereInput.trim());
                          setMatiere(quickMatiereInput.trim());
                          setQuickMatiereInput('');
                          setIsAddingNewMatiere(false);
                        }
                      }}
                      className="px-2.5 py-1 bg-blue-600 text-white rounded-lg text-xs font-bold"
                    >
                      OK
                    </button>
                  </div>
                ) : (
                  <select
                    value={matiere}
                    onChange={(e) => setMatiere(e.target.value)}
                    className="w-full px-3 py-2 border border-slate-200 rounded-lg text-sm outline-none focus:border-blue-500 bg-white"
                  >
                    {matieres.map((m) => (
                      <option key={m} value={m}>
                        {m}
                      </option>
                    ))}
                  </select>
                )}
              </div>

              {/* Percentage Setup */}
              <div className="bg-slate-50 p-4 rounded-xl border border-slate-200 space-y-3">
                <div className="flex items-center justify-between">
                  <label className="text-xs font-bold text-slate-800 flex items-center gap-1.5">
                    <Percent className="w-4 h-4 text-emerald-600" />
                    <span>Pourcentage du Professeur (%)</span>
                  </label>
                  <span className="text-base font-extrabold text-emerald-700">
                    {pourcentage}%
                  </span>
                </div>

                {/* Quick percentage buttons */}
                <div className="flex gap-2">
                  {[50, 55, 60, 65, 70].map((p) => (
                    <button
                      key={p}
                      type="button"
                      onClick={() => setPourcentage(p)}
                      className={`flex-1 py-1.5 text-xs font-bold rounded-lg border transition-all ${
                        pourcentage === p
                          ? 'bg-emerald-600 text-white border-emerald-600 shadow-xs'
                          : 'bg-white text-slate-700 border-slate-200 hover:bg-slate-100'
                      }`}
                    >
                      {p}%
                    </button>
                  ))}
                </div>

                {/* Range Slider */}
                <input
                  type="range"
                  min="20"
                  max="90"
                  step="5"
                  value={pourcentage}
                  onChange={(e) => setPourcentage(Number(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />

                <div className="flex items-center justify-between text-xs pt-1 border-t border-slate-200/70 text-slate-600">
                  <span>Part Prof : <strong className="text-emerald-700">{pourcentage}%</strong></span>
                  <span>Part Centre : <strong className="text-blue-700">{100 - pourcentage}%</strong></span>
                </div>
              </div>

              <div className="flex items-center justify-end gap-3 pt-3 border-t border-slate-100">
                <button
                  type="button"
                  onClick={() => setIsModalOpen(false)}
                  className="px-4 py-2 border border-slate-200 text-slate-600 rounded-lg text-sm font-semibold hover:bg-slate-50"
                >
                  Annuler
                </button>
                <button
                  type="submit"
                  className="px-5 py-2 bg-blue-600 hover:bg-blue-700 text-white rounded-lg text-sm font-semibold shadow-xs"
                >
                  Enregistrer le professeur
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* Floating Success Toast */}
      {toastMessage && (
        <div className="fixed top-20 right-6 z-50 flex items-center gap-2.5 px-4 py-3 bg-emerald-600 text-white text-sm font-semibold rounded-xl shadow-lg animate-in slide-in-from-top-3 duration-200">
          <FaCircleCheck className="w-4 h-4 text-emerald-200 shrink-0" />
          <span>{toastMessage}</span>
        </div>
      )}

      {/* Delete Confirmation Modal */}
      <DeleteConfirmModal
        isOpen={!!deleteTarget}
        title="Supprimer l'Enseignant"
        itemType="le professeur"
        itemName={deleteTarget?.name}
        onConfirm={() => {
          if (deleteTarget) {
            deleteProfesseur(deleteTarget.id);
            showToast(`${deleteTarget.name} a été retiré avec succès.`);
            setDeleteTarget(null);
          }
        }}
        onClose={() => setDeleteTarget(null)}
      />
    </div>
  );
}
